import {api} from '../api.mjs'; import fs from 'node:fs'; import path from 'node:path';
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
const cid=fs.readFileSync('cid','utf8').trim(); const stub=path.resolve('gate/stub.mjs');
const mk=name=>api('POST',`/companies/${cid}/agents`,{name,role:'general',adapterType:'process',adapterConfig:{command:'node',args:[stub],cwd:path.resolve('gate')}});
const lead=await mk('gate-lead'); const w=await mk('gate-worker');
await api('PATCH',`/agents/${w.id}`,{reportsTo:lead.id});
console.log('lead',lead.id,lead.status, JSON.stringify(lead.adapterConfig));
const c1=await api('POST',`/companies/${cid}/issues`,{title:'gate child 1',assigneeAgentId:w.id,status:'todo'});
const c2=await api('POST',`/companies/${cid}/issues`,{title:'gate child 2',assigneeAgentId:w.id,status:'todo'});
const p=await api('POST',`/companies/${cid}/issues`,{title:'gate parent',assigneeAgentId:lead.id,status:'todo',blockedByIssueIds:[c1.id,c2.id]});
for(const c of [c1,c2]) await api('PATCH',`/issues/${c.id}`,{parentId:p.id});
console.log('parent status',p.status,'blockedBy',JSON.stringify(p.blockedByIssueIds||p.blockedBy?.map?.(b=>b.id)));
await sleep(20000);
const before=await api('GET',`/issues/${p.id}/runs`); console.log('parent runs before unblock',before.length, before.map(r=>r.invocationSource+':'+r.status).join(','));
const pp=await api('GET',`/issues/${p.id}`); console.log('parent status now',pp.status);
const t0=Date.now();
await Promise.all([api('PATCH',`/issues/${c1.id}`,{status:'done'}),api('PATCH',`/issues/${c2.id}`,{status:'done'})]);
console.log('children done in',Date.now()-t0,'ms');
await sleep(45000);
const after=await api('GET',`/issues/${p.id}/runs`);
const leadRuns=(await api('GET',`/companies/${cid}/heartbeat-runs?agentId=${lead.id}`));
console.log('parent runs after',after.length, after.map(r=>r.invocationSource+':'+r.status+':'+r.createdAt).join(' | '));
const lr=Array.isArray(leadRuns)?leadRuns:(leadRuns.items||[]);
console.log('lead runs total',lr.filter(r=>r.agentId===lead.id).map(r=>r.invocationSource+':'+(r.contextIssueId===p.id?'parent':r.contextIssueId)+':'+r.createdAt).join(' | '));
fs.writeFileSync('gate/ids.json',JSON.stringify({lead:lead.id,worker:w.id,p:p.id,c1:c1.id,c2:c2.id}));
