// Agent instructions file (plan B): everything an agent must know on every run, injected by Paperclip
// through the agent's own `instructionsFilePath`, so it does not depend on the working directory.
//
// P4 lesson: giving only the paths of memory files ("read these first") lets the model skip them on a
// simple task. So the file carries the *contents* of the global profile and of the agent's memory, and
// is regenerated whenever they change: after every run (plugin), after memory consolidation (plugin),
// and when the user edits the profile or memory, or a lead records a decision (local service).
//
// Shared by the local service (scripts/lib/department.mjs) and the team-layer plugin (bundled).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
// Works both from scripts/lib and when bundled into plugins/team-layer/dist (repo root is found by marker).
function findRepoRoot() {
  for (const start of [here, process.cwd()]) {
    let d = start;
    for (let i = 0; i < 8; i++) {
      if (fs.existsSync(path.join(d, "skills", "lead", "SKILL.md"))) return d;
      const up = path.dirname(d);
      if (up === d) break;
      d = up;
    }
  }
  return path.resolve(here, "..", "..");
}

export const PROFILE_KEYS = [
  ["user", "user.md", "关于用户"],
  ["decisions", "decisions.md", "用户定过的事（必须照做，不要再问）"],
  ["declined", "declined.md", "用户拒绝过的事（不要再提）"],
  ["askfirst", "askfirst.md", "先问清单（这些情况必须先停下来问）"],
];
const MEMORY_FILES = [
  ["identity.md", "你是谁", 3000],
  ["style.md", "用户要求的工作方式（必须遵守）", 4000],
  ["user.md", "你了解到的用户偏好", 4000],
  ["notes.md", "以往经验", 7000],
];
const PROFILE_CAP = 6000;

const runtimeDir = (cwd) => path.join(cwd, ".agentself");
export const instructionsPath = (cwd) => path.join(runtimeDir(cwd), "instructions.md");
const runtimeMetaPath = (cwd) => path.join(runtimeDir(cwd), "runtime.json");
const posix = (p) => p.split(path.sep).join("/");

const read = (p, cap) => {
  try {
    const t = fs.readFileSync(p, "utf8").trim();
    return t.length > cap ? `${t.slice(0, cap)}\n\n（以下省略，完整内容见 ${posix(p)}）` : t;
  } catch {
    return "";
  }
};
const stripFrontmatter = (md) => md.replace(/^---\n[\s\S]*?\n---\n+/, "");
/** Demote headings so embedded files do not break the document outline. */
const demote = (md) => md.replace(/^(#{1,4}) /gm, "$1## ");

function listTopics(memDir) {
  try {
    return fs
      .readdirSync(path.join(memDir, "topics"))
      .filter((f) => f.endsWith(".md"))
      .sort();
  } catch {
    return [];
  }
}

/** Render the full instructions for one agent. Pure apart from reading files. */
export function renderInstructions({ role, cwd, home, repoRoot = findRepoRoot() }) {
  const isLead = role === "lead";
  const memDir = path.join(cwd, "memory");
  const profileDir = path.join(home, "profile");
  const skill = stripFrontmatter(fs.readFileSync(path.join(repoRoot, "skills", isLead ? "lead" : "employee", "SKILL.md"), "utf8"));

  const profile = PROFILE_KEYS.map(([, file, title]) => {
    const body = read(path.join(profileDir, file), PROFILE_CAP);
    return `### ${title}\n\n${body ? demote(body) : "（空）"}`;
  }).join("\n\n");

  const memory = MEMORY_FILES.map(([file, title, cap]) => {
    const body = read(path.join(memDir, file), cap);
    return `### ${title}（${file}）\n\n${body ? demote(body) : "（空）"}`;
  }).join("\n\n");

  const topics = listTopics(memDir);
  const p = (f) => posix(path.join(memDir, f));
  const writeBack = isLead
    ? `- 这个领域里关于用户的了解、派活和验收的经验 → 追加到 \`${p("notes.md")}\`（一条一行，"- " 开头）
- 某个主题的长期背景 → \`${p("topics")}/<主题>.md\`
- 用户说"以后都这样"的决定、明确拒绝的做法 → 不要写进自己的记忆，用 record_decision 记进全局档案`
    : `- 用户明确表达的偏好 → 追加到 \`${p("user.md")}\`
- 以后还用得上的经验 → 追加到 \`${p("notes.md")}\`（一条一行，"- " 开头）
- 某个主题的详细资料 → \`${p("topics")}/<主题>.md\``;

  return `<!-- generated by Agentself; regenerated whenever memory or the profile changes; edits are overwritten -->
以下是你的全部工作说明、用户的全局档案和你自己的记忆。它随你的身份配置注入每次运行，不依赖你在哪个目录里运行。**下面的档案和记忆已经是最新内容，每次任务都要照做**；交付时一句话说明用到了哪条。

## 用户的全局档案（所有主管和员工共用）

${profile}

## 你自己的记忆

记忆目录：\`${posix(memDir)}\`。它不一定是你现在的工作目录：任务可能在别的目录里运行，记忆一律用这里的绝对路径读写，不要读写当前目录下的 \`memory/\`、\`CLAUDE.md\`、\`AGENTS.md\`。

${memory}

### 主题资料

${topics.length ? `和任务相关的再读：${topics.map((f) => `\`${p("topics")}/${f}\``).join("、")}` : "（还没有）"}

### 收工前写回

${writeBack}
- 不要写密钥、令牌、密码；不要改 identity.md 和 style.md（有建议写在评论里）

---

${skill}`;
}

/** Write (or rewrite) the instructions file; remembers the role so later refreshes need no lookup. */
export function writeInstructions({ role, cwd, home, adapterType, repoRoot }) {
  fs.mkdirSync(runtimeDir(cwd), { recursive: true });
  fs.writeFileSync(runtimeMetaPath(cwd), JSON.stringify({ role, adapterType: adapterType ?? null }, null, 2));
  const f = instructionsPath(cwd);
  const text = renderInstructions({ role, cwd, home, repoRoot });
  fs.writeFileSync(`${f}.tmp`, text);
  fs.renameSync(`${f}.tmp`, f);
  return f;
}

/** Regenerate one agent's instructions if it has an Agentself runtime (no-op otherwise). */
export function refreshInstructions(cwd, home) {
  let meta;
  try {
    meta = JSON.parse(fs.readFileSync(runtimeMetaPath(cwd), "utf8"));
  } catch {
    return false;
  }
  writeInstructions({ role: meta.role, cwd, home, adapterType: meta.adapterType });
  return true;
}

/** Regenerate every agent under <home>/workspaces/<team>/<member> (after a profile change). */
export function refreshAllInstructions(home) {
  const root = path.join(home, "workspaces");
  let n = 0;
  if (!fs.existsSync(root)) return 0;
  for (const team of fs.readdirSync(root)) {
    const teamDir = path.join(root, team);
    if (!fs.statSync(teamDir).isDirectory()) continue;
    for (const member of fs.readdirSync(teamDir)) {
      const cwd = path.join(teamDir, member);
      try {
        if (fs.statSync(cwd).isDirectory() && refreshInstructions(cwd, home)) n++;
      } catch {
        /* skip unreadable */
      }
    }
  }
  return n;
}
